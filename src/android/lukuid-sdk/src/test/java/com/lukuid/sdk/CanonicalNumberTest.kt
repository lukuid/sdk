class CanonicalNumberTest {
    @Test
    fun roundsExactTiesToEvenLikeTheDevice() {
        assertEquals("1023.12", CanonicalNumber.fixed(1023.125, 2))
        assertEquals("0.38", CanonicalNumber.fixed(0.375, 2))
        assertEquals("0.007812", CanonicalNumber.fixed(0.0078125, 6))
    }

    @Test
    fun keepsTheSignOfNegativeValuesThatRoundToZero() {
        assertEquals("-0.00", CanonicalNumber.fixed(-0.002, 2))
        assertEquals("-0.00", CanonicalNumber.fixed(-0.0, 2))
    }

